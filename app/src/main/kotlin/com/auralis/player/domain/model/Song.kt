package com.auralis.player.domain.model

import com.auralis.player.data.local.dao.SongWithMetadata

data class Song(
    val id: Long,
    val documentId: String,
    val folderId: Long,
    val title: String,
    val artistId: Long?,
    val artistName: String?,
    val albumId: Long?,
    val albumTitle: String?,
    val genreId: Long?,
    val composer: String?,
    val year: Int?,
    val trackNumber: Int?,
    val totalTracks: Int?,
    val discNumber: Int,
    val totalDiscs: Int?,
    val durationMs: Long,
    val isFavorite: Boolean,
    val playCount: Int,
    val lastPlayedAt: Long?,
    /** Absolute path of the album cover file, or null. */
    val artworkUri: String? = null,
    val dateAdded: Long = 0L,
    val genreName: String? = null,
    val mimeType: String? = null,
    val bitrateKbps: Int? = null,
    val sampleRateHz: Int? = null,
    val displayName: String? = null,
)

fun SongWithMetadata.toDomain(): Song = Song(
    id = song.id,
    documentId = song.documentId,
    folderId = song.folderId,
    title = song.title,
    artistId = song.artistId,
    artistName = artistName,
    albumId = song.albumId,
    albumTitle = albumTitle,
    genreId = song.genreId,
    composer = song.composer,
    year = song.year,
    trackNumber = song.trackNumber,
    totalTracks = song.totalTracks,
    discNumber = song.discNumber,
    totalDiscs = song.totalDiscs,
    durationMs = song.durationMs,
    isFavorite = song.isFavorite,
    playCount = song.playCount,
    lastPlayedAt = song.lastPlayedAt,
    artworkUri = artworkUri,
    dateAdded = song.dateAdded,
    genreName = genreName,
    mimeType = song.mimeType,
    bitrateKbps = song.bitrateKbps,
    sampleRateHz = song.sampleRateHz,
    displayName = song.displayName,
)
